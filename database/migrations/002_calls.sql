CREATE TABLE IF NOT EXISTS calls (
 id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 shop_id VARCHAR(100) NOT NULL,
 call_id VARCHAR(255) CHARACTER SET utf8mb4 COLLATE utf8mb4_bin NOT NULL UNIQUE,
 transcript TEXT NULL,
 payload JSON NOT NULL,
 extraction JSON NULL,
 received_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
 CONSTRAINT calls_shop_fk FOREIGN KEY (shop_id) REFERENCES shops(shop_id),
 INDEX calls_received (received_at)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
ALTER TABLE orders MODIFY COLUMN call_id VARCHAR(255) CHARACTER SET utf8mb4 COLLATE utf8mb4_bin NOT NULL;
