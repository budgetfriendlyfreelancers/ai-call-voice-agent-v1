CREATE DATABASE IF NOT EXISTS voiceshop CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
USE voiceshop;
CREATE TABLE IF NOT EXISTS shops (
 shop_id VARCHAR(100) PRIMARY KEY, shop_name VARCHAR(255) NOT NULL, config_json LONGTEXT NOT NULL,
 is_demo TINYINT NOT NULL DEFAULT 0, updated_at DATETIME NOT NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
CREATE TABLE IF NOT EXISTS orders (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, shop_id VARCHAR(100) NOT NULL,
 call_id VARCHAR(255) CHARACTER SET utf8mb4 COLLATE utf8mb4_bin NOT NULL UNIQUE,
 language VARCHAR(30) NOT NULL,
 status ENUM('DRAFT','NEEDS_DETAILS','AWAITING_MERCHANT_APPROVAL','CONFIRMED','READY_FOR_DELIVERY','COMPLETED') NOT NULL,
 customer_name VARCHAR(255) NOT NULL, customer_phone VARCHAR(50) NOT NULL,
 address_json LONGTEXT NOT NULL, delivery_choice VARCHAR(100) NOT NULL, payment_choice VARCHAR(100) NOT NULL,
 requested_time VARCHAR(255) NOT NULL, missing_fields_json LONGTEXT NOT NULL, flags_json LONGTEXT NOT NULL,
 order_json LONGTEXT NOT NULL, is_demo TINYINT NOT NULL DEFAULT 0,
 created_at DATETIME NOT NULL, updated_at DATETIME NOT NULL,
 FOREIGN KEY (shop_id) REFERENCES shops(shop_id), INDEX shop_status (shop_id,status), INDEX created (created_at)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
CREATE TABLE IF NOT EXISTS order_items (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, order_id BIGINT UNSIGNED NOT NULL,
 sku VARCHAR(100) NOT NULL, qty DECIMAL(12,3) NOT NULL, unit VARCHAR(50) NOT NULL,
 options_json LONGTEXT NOT NULL, raw_text TEXT NOT NULL, is_unknown_item TINYINT NOT NULL DEFAULT 0,
 FOREIGN KEY (order_id) REFERENCES orders(id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
CREATE TABLE IF NOT EXISTS order_status_log (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, order_id BIGINT UNSIGNED NOT NULL,
 from_status VARCHAR(50) NOT NULL, to_status VARCHAR(50) NOT NULL, changed_by VARCHAR(100) NOT NULL,
 changed_at DATETIME NOT NULL, note TEXT NOT NULL,
 FOREIGN KEY (order_id) REFERENCES orders(id) ON DELETE CASCADE, INDEX order_history (order_id,changed_at)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
